"""Inventory every retail .menu file for the RmlUi migration.

Usage: py -3 inventory.py <GameData/base> <output dir>

Later pk3 files override earlier ones, matching the engine's search order.
"""
from __future__ import annotations

import json
import sys
import zipfile
from collections import Counter, defaultdict
from pathlib import Path

from menu_parser import parse_text

ITEM_TYPES = ["TEXT", "BUTTON", "RADIOBUTTON", "CHECKBOX", "EDITFIELD", "COMBO", "LISTBOX", "MODEL",
              "OWNERDRAW", "NUMERICFIELD", "SLIDER", "YESNO", "MULTI", "BIND", "TEXTSCROLL"]
SCRIPT_KEYS = ["action", "doubleclick", "accept", "mouseenter", "mouseexit", "mouseentertext",
               "mouseexittext", "onfocus", "leavefocus", "selectnext", "selectprev",
               "onopen", "onclose", "onesc", "onaccept"]


def game_files(base: Path) -> dict[str, tuple[Path, str]]:
    """Map lowercase game path to (pk3, entry), letting later archives win."""
    files: dict[str, tuple[Path, str]] = {}
    for pk3 in sorted(base.glob("*.pk3"), key=lambda p: p.name.lower()):
        with zipfile.ZipFile(pk3) as z:
            for name in z.namelist():
                if not name.endswith("/"):
                    files[name.lower()] = (pk3, name)
    return files


def read(entry: tuple[Path, str]) -> str:
    with zipfile.ZipFile(entry[0]) as z:
        return z.read(entry[1]).decode("latin-1")


def item_type(item) -> str:
    if item.get("ownerdraw"):  # the keyword sets the type, as ItemParse_ownerdraw does
        return "OWNERDRAW"
    raw = str(item.get("type", "0"))
    if raw.isdigit() and int(raw) < len(ITEM_TYPES):
        return ITEM_TYPES[int(raw)]
    return raw.replace("ITEM_TYPE_", "")


def scripts(node):
    for key in SCRIPT_KEYS:
        yield from node.get(key) or []


def inventory_set(name: str, files: dict, paths: list[str]) -> dict:
    types, verbs, ui_scripts, ownerdraws, feeders = Counter(), Counter(), Counter(), Counter(), Counter()
    cvars, art, models, sounds = Counter(), Counter(), Counter(), Counter()
    menus, warnings = [], []
    for path in paths:
        parsed = parse_text(read(files[path]), path)
        warnings += [f"{path}: {w}" for w in parsed.warnings]
        for menu in parsed.menus:
            used = Counter(item_type(i) for i in menu.items)
            menus.append({"file": path, "name": menu.get("name", "?"), "items": len(menu.items),
                          "rect": menu.get("rect"), "fullscreen": menu.get("fullscreen", "0"),
                          "popup": bool(menu.get("popup")), "types": dict(used)})
            types.update(used)
            for node in [menu, *menu.items]:
                for cmd in scripts(node):
                    verbs[cmd[0]] += 1
                    if cmd[0] == "uiscript" and len(cmd) > 1:
                        ui_scripts[cmd[1]] += 1
                    if cmd[0] == "setcvar" and len(cmd) > 1:
                        cvars[cmd[1]] += 1
                    if cmd[0] == "play" and len(cmd) > 1:
                        sounds[cmd[1]] += 1
                for key in ("background", "asset_shader"):
                    if node.get(key):
                        art[node.get(key)] += 1
            for item in menu.items:
                if item.get("ownerdraw"):
                    ownerdraws[item.get("ownerdraw")] += 1
                if item.get("feeder"):
                    feeders[item.get("feeder")] += 1
                if item.get("cvar"):
                    cvars[item.get("cvar")] += 1
                if item.get("asset_model"):
                    models[item.get("asset_model")] += 1

    missing = []
    for image in art:
        low = image.lower().replace("\\", "/")
        stem = low.rsplit(".", 1)[0]
        if not any(f"{stem}.{ext}" in files for ext in ("png", "tga", "jpg")):
            missing.append(image)
    return {"set": name, "menu_files": len(paths), "menus": menus, "item_types": types,
            "script_verbs": verbs, "ui_scripts": ui_scripts, "ownerdraws": ownerdraws,
            "feeders": feeders, "cvars": cvars, "art": art, "models": models, "sounds": sounds,
            "art_not_plain_images": sorted(missing), "warnings": warnings}


def table(counter: Counter, heading: str) -> list[str]:
    lines = [f"| {heading} | Uses |", "| --- | --- |"]
    lines += [f"| `{k}` | {v} |" for k, v in counter.most_common()]
    return lines + [""]


def markdown(sets: list[dict]) -> str:
    out = ["# Menu inventory", "",
           "Generated by `tools/menu_converter/inventory.py` from the retail pk3 files.", ""]
    for s in sets:
        items = sum(m["items"] for m in s["menus"])
        out += [f"## {s['set']}", "",
                f"{s['menu_files']} files, {len(s['menus'])} menus, {items} items, "
                f"{len(s['art'])} images, {len(s['cvars'])} cvars, {len(s['ui_scripts'])} uiScripts, "
                f"{len(s['ownerdraws'])} ownerdraws, {len(s['feeders'])} feeders, "
                f"{len(s['warnings'])} parser warnings.", "",
                "| Menu | File | Items | Popup |", "| --- | --- | --- | --- |"]
        out += [f"| `{m['name']}` | `{m['file']}` | {m['items']} | {'yes' if m['popup'] else ''} |"
                for m in s["menus"]]
        out.append("")
        out += table(s["item_types"], "Item type") + table(s["script_verbs"], "Script verb")
        out += table(s["ui_scripts"], "uiScript") + table(s["ownerdraws"], "Ownerdraw")
        out += table(s["feeders"], "Feeder")
        if s["art_not_plain_images"]:
            out += ["Art names with no plain image file, so they resolve through a `.shader` or are missing:", ""]
            out += [f"- `{a}`" for a in s["art_not_plain_images"]] + [""]
    return "\n".join(out)


def main():
    base, out_dir = Path(sys.argv[1]), Path(sys.argv[2])
    files = game_files(base)
    groups = defaultdict(list)
    for path in sorted(files):
        if path.endswith(".menu"):
            parts = path.split("/")
            if parts[0] == "ui" and len(parts) == 2:
                groups["Single player"].append(path)
            elif parts[:2] == ["ui", "jamp"] and len(parts) == 3:
                groups["Multiplayer UI"].append(path)
            else:
                groups["Other"].append(path)
    sets = [inventory_set(name, files, paths) for name, paths in groups.items()]
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "menu-inventory.md").write_text(markdown(sets), encoding="utf-8")
    (out_dir / "menu-inventory.json").write_text(json.dumps(sets, indent=1), encoding="utf-8")
    for s in sets:
        print(s["set"], s["menu_files"], "files", len(s["menus"]), "menus",
              sum(m["items"] for m in s["menus"]), "items", len(s["warnings"]), "warnings")
        for w in s["warnings"][:8]:
            print("  ", w)


if __name__ == "__main__":
    main()
